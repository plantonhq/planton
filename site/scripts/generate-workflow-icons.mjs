/** Embed the hero diagram's marks (the providers it draws, Planton and GitHub)
 * from their canonical SVGs, so the diagram has no runtime CDN dependency.
 * `--check` fails the build when the embedded bytes drift from the sources. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { HERO } from '../src/data/homepage-experience.ts';
const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const providers = path.join(site, 'public/_site/images/providers');
const sources = [
  ...HERO.providerMarks.map((p) => [p, `${p === 'digitalocean' ? 'digital-ocean' : p}.svg`]),
  ['planton', 'planton.svg'],
  ['github', 'github-dark.svg'],
];
const registry = {};
for (const [key, file] of sources) {
  const svg = fs.readFileSync(path.join(providers, file), 'utf8');
  if (!svg.includes('<svg') || /<(script|foreignObject)\b|(?:href|xlink:href)=["']https?:/i.test(svg))
    throw Error(`Invalid embedded icon: ${file}`);
  registry[key] = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
}
const destination = path.join(site, 'src/data/workflow-icons.ts');
const output = `// Generated by scripts/generate-workflow-icons.mjs from the canonical SVGs.\n// Keep the source SVGs authoritative; do not edit embedded icon data.\nexport const WORKFLOW_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(registry, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output)
    throw Error('Workflow icons are stale. Run generate-workflow-icons.mjs.');
} else fs.writeFileSync(destination, output);
console.log(`PASS: ${Object.keys(registry).length} hero icons.`);
