/** Embed only the selected canonical icons. Both SVG renderers consume the same
 * bytes; no runtime CDN dependency, catalog crawl, or private-repo asset path. */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ARCHITECTURES, PROVIDER_ORDER } from '../src/data/architecture-stories.ts';
const site = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const registry = {};
for (const provider of PROVIDER_ORDER) {
  const files = [[provider, path.join(site, 'public/_site/images/providers', `${provider === 'digitalocean' ? 'digital-ocean' : provider}.svg`)]];
  for (const resource of ARCHITECTURES[provider].architecture.resources) {
    const owner = resource.kind.startsWith('Kubernetes') ? 'kubernetes' : provider;
    files.push([resource.kind, path.join(site, '../catalog', owner, resource.kind.toLowerCase(), 'logo.svg')]);
  }
  for (const [key, file] of files) {
    const svg = fs.readFileSync(file, 'utf8');
    if (!svg.includes('<svg') || /<(script|foreignObject)\b|(?:href|xlink:href)=["']https?:/i.test(svg)) throw Error(`Invalid embedded icon: ${file}`);
    registry[key] = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
    // The canonical AWS mark has pale lettering for dark surfaces. Derive its
    // light-surface treatment from the same paths; leave the orange smile intact.
    if (key === 'aws') registry['aws-light'] = `data:image/svg+xml;base64,${Buffer.from(svg.replaceAll('fill="#EBEBEB"', 'fill="#232F3E"')).toString('base64')}`;
  }
}
const destination = path.join(site, 'src/data/workflow-icons.ts');
const output = `// Generated by scripts/generate-workflow-icons.mjs from the canonical catalog SVGs.\n// Keep the source SVGs authoritative; do not edit embedded icon data.\nexport const WORKFLOW_ICONS: Readonly<Record<string, string>> = ${JSON.stringify(registry, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output) throw Error('Workflow icons are stale. Run generate-workflow-icons.mjs.');
} else fs.writeFileSync(destination, output);
console.log(`PASS: ${Object.keys(registry).length} canonical workflow icons.`);
