// Package tfoverride generates the per-job provider-override file for the
// OpenTofu/Terraform execution path.
//
// The catalog's modules deliberately ship an EMPTY `provider "aws" {}` block:
// region and credentials are injected as environment variables at execution
// time (see pkg/iac/iacinput/providerenvvars). That works only for provider
// arguments that have an environment form. The provider-block surface this
// package carries -- the assume-role chain, default tags, per-service endpoint
// overrides, and retry tuning -- has no complete environment form (assume_role
// has none at all), so it rides Terraform's override-file convention instead:
// a file whose name ends in `_override.tf` merges its provider block's
// arguments into the module's empty block at load time, with zero changes to
// any module.
//
// One mechanism carries ALL provider-block arguments, including the ones that
// do have environment forms (default_tags, retry_mode): a single generated
// file is one legible artifact showing the whole effective provider block, and
// it avoids the per-tag env-var encoding edge cases (TF_AWS_DEFAULT_TAGS_* is
// unusable for tag keys that are not valid env-var names).
//
// The writer deliberately never emits region or credentials: region stays on
// the env path (a provider-block region would outrank AWS_REGION and defeat
// the resource-region-beats-connection rule), and credentials stay on the
// existing env/exchange paths -- nothing long-lived is ever written to disk.
package tfoverride

import (
	"os"
	"path/filepath"
	"sort"

	"github.com/hashicorp/hcl/v2/hclwrite"
	"github.com/pkg/errors"
	awsprovider "github.com/plantonhq/planton/catalog/aws"
	"github.com/plantonhq/planton/pkg/iac/iacinput/providerenvvars"
	"github.com/zclconf/go-cty/cty"
)

// OverrideFileName is the generated file's name. The `_override.tf` suffix is
// what makes Terraform merge it into the module's own provider block instead
// of treating it as a duplicate block (which would fail module load).
const OverrideFileName = "_planton_override.tf"

const fileHeader = `# Generated by Planton at execution time from the IaC input's provider_config.
# Carries the provider-block arguments that cannot ride environment variables
# (assume-role chain, endpoint overrides) plus the rest of the provider-block
# surface so the whole effective provider block is visible in one place.
# Never carries region or credentials -- those are injected as environment
# variables. Regenerated on every run; safe to delete.
`

// WriteProviderOverrideFile writes (or removes) the module's provider-override
// file from the IaC input's provider config. It is idempotent in both
// directions: when the config carries provider-block arguments the file is
// written fresh, and when it carries none any stale file from a previous run
// is removed -- load-bearing for module directories that outlive a run (a
// user's own checkout, the CLI's zip cache), where a leftover override would
// silently apply yesterday's provider settings to tomorrow's run.
//
// Returns true when the file exists after the call. Callers that hand the
// module directory back to the user (the standalone CLI) should remove the
// file after the run regardless.
func WriteProviderOverrideFile(modulePath string, iacInputYaml string) (bool, error) {
	overridePath := filepath.Join(modulePath, OverrideFileName)

	config, err := providerenvvars.ExtractAwsProviderConfig(iacInputYaml)
	if err != nil {
		return false, err
	}

	if !hasProviderBlockArgs(config) {
		if err := os.Remove(overridePath); err != nil && !os.IsNotExist(err) {
			return false, errors.Wrapf(err, "failed to remove stale %s", OverrideFileName)
		}
		return false, nil
	}

	content := append([]byte(fileHeader), renderAwsProviderBlock(config)...)
	if err := os.WriteFile(overridePath, content, 0644); err != nil {
		return false, errors.Wrapf(err, "failed to write %s", OverrideFileName)
	}
	return true, nil
}

// hasProviderBlockArgs reports whether the config carries any argument that
// belongs in the provider block (as opposed to the env-var surface).
func hasProviderBlockArgs(config *awsprovider.AwsProviderConfig) bool {
	if config == nil {
		return false
	}
	return len(config.GetAssumeRoleChain()) > 0 ||
		len(config.GetDefaultTags().GetTags()) > 0 ||
		len(config.GetEndpoints()) > 0 ||
		config.MaxRetries != nil ||
		config.GetRetryMode() != ""
}

// renderAwsProviderBlock renders the provider "aws" override block with
// hclwrite (correct quoting/escaping for arbitrary tag values and policy
// JSON). Map keys are emitted in sorted order so output is deterministic and
// golden-testable.
func renderAwsProviderBlock(config *awsprovider.AwsProviderConfig) []byte {
	f := hclwrite.NewEmptyFile()
	body := f.Body().AppendNewBlock("provider", []string{"aws"}).Body()

	// Hops are emitted in declaration order: Terraform evaluates repeated
	// assume_role blocks as a chain (each hop assumed with the previous hop's
	// credentials), which is exactly the proto field's contract.
	for _, hop := range config.GetAssumeRoleChain() {
		hopBody := body.AppendNewBlock("assume_role", nil).Body()
		hopBody.SetAttributeValue("role_arn", cty.StringVal(hop.GetRoleArn()))
		if hop.GetSessionName() != "" {
			hopBody.SetAttributeValue("session_name", cty.StringVal(hop.GetSessionName()))
		}
		if hop.GetExternalId() != "" {
			hopBody.SetAttributeValue("external_id", cty.StringVal(hop.GetExternalId()))
		}
		if hop.GetDuration() != "" {
			hopBody.SetAttributeValue("duration", cty.StringVal(hop.GetDuration()))
		}
		if hop.GetPolicy() != "" {
			hopBody.SetAttributeValue("policy", cty.StringVal(hop.GetPolicy()))
		}
		if len(hop.GetPolicyArns()) > 0 {
			hopBody.SetAttributeValue("policy_arns", stringList(hop.GetPolicyArns()))
		}
		if len(hop.GetTags()) > 0 {
			hopBody.SetAttributeValue("tags", stringMap(hop.GetTags()))
		}
		if len(hop.GetTransitiveTagKeys()) > 0 {
			hopBody.SetAttributeValue("transitive_tag_keys", stringList(hop.GetTransitiveTagKeys()))
		}
		if hop.GetSourceIdentity() != "" {
			hopBody.SetAttributeValue("source_identity", cty.StringVal(hop.GetSourceIdentity()))
		}
	}

	if tags := config.GetDefaultTags().GetTags(); len(tags) > 0 {
		body.AppendNewBlock("default_tags", nil).Body().SetAttributeValue("tags", stringMap(tags))
	}

	if endpoints := config.GetEndpoints(); len(endpoints) > 0 {
		endpointsBody := body.AppendNewBlock("endpoints", nil).Body()
		for _, service := range sortedKeys(endpoints) {
			// The service name is the endpoints block's attribute name; an
			// unknown name fails `tofu init`/`plan` loudly -- the desired
			// behavior, since a mis-keyed override would otherwise silently
			// send traffic to the public endpoint.
			endpointsBody.SetAttributeValue(service, cty.StringVal(endpoints[service]))
		}
	}

	if config.MaxRetries != nil {
		body.SetAttributeValue("max_retries", cty.NumberIntVal(int64(config.GetMaxRetries())))
	}
	if config.GetRetryMode() != "" {
		body.SetAttributeValue("retry_mode", cty.StringVal(config.GetRetryMode()))
	}

	return f.Bytes()
}

func stringList(values []string) cty.Value {
	list := make([]cty.Value, 0, len(values))
	for _, v := range values {
		list = append(list, cty.StringVal(v))
	}
	return cty.ListVal(list)
}

func stringMap(m map[string]string) cty.Value {
	vals := make(map[string]cty.Value, len(m))
	for k, v := range m {
		vals[k] = cty.StringVal(v)
	}
	return cty.MapVal(vals)
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}
