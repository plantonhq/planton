package catalogkindreflect

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"
)

var updateSnapshot = flag.Bool("update", false, "regenerate testdata/registry_numbers.txt from the live registry")

const snapshotPath = "testdata/registry_numbers.txt"

const snapshotHeader = `# CatalogKind number snapshot -- generated by registry_snapshot_test.go (-update); do not edit by hand.
#
# Enum numbers are transport-level identity: binary payloads and in-flight
# messages decode through them, so a number that moves silently can decode
# stored or in-flight data as the WRONG kind. This snapshot makes every
# numbering change a deliberate, reviewable act:
#
#   - Pre-launch (alpha posture), renumbering is LEGAL but never invisible:
#     regenerate this file with -update in the same change and say why in
#     the change's description.
#   - Once kinds graduate to beta/stable, their numbers freeze: a diff in
#     this file for a graduated kind is a defect, not a chore.
#
# One line per kind: <enum_name>=<number>, sorted by number.
`

func currentSnapshot() map[string]int32 {
	snap := make(map[string]int32)
	for _, kind := range KindsList() {
		snap[kind.String()] = int32(kind.Number())
	}
	return snap
}

func renderSnapshot(snap map[string]int32) string {
	type entry struct {
		name string
		num  int32
	}
	entries := make([]entry, 0, len(snap))
	for name, num := range snap {
		entries = append(entries, entry{name, num})
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].num < entries[j].num })
	var b strings.Builder
	b.WriteString(snapshotHeader)
	for _, e := range entries {
		fmt.Fprintf(&b, "%s=%d\n", e.name, e.num)
	}
	return b.String()
}

func parseSnapshot(t *testing.T, raw string) map[string]int32 {
	t.Helper()
	snap := make(map[string]int32)
	for i, line := range strings.Split(raw, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		name, numStr, ok := strings.Cut(line, "=")
		if !ok {
			t.Fatalf("%s:%d: malformed line %q", snapshotPath, i+1, line)
		}
		num, err := strconv.ParseInt(numStr, 10, 32)
		if err != nil {
			t.Fatalf("%s:%d: bad number in %q: %v", snapshotPath, i+1, line, err)
		}
		snap[name] = int32(num)
	}
	return snap
}

// TestRegistryNumberSnapshot pins every kind's enum number against a
// committed snapshot so numbering changes are always deliberate and visible
// in review -- never a silent side effect of an unrelated edit.
func TestRegistryNumberSnapshot(t *testing.T) {
	current := currentSnapshot()
	if len(current) == 0 {
		t.Fatal("registry walk produced no kinds -- the snapshot gate is broken")
	}

	if *updateSnapshot {
		if err := os.MkdirAll(filepath.Dir(snapshotPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(snapshotPath, []byte(renderSnapshot(current)), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("regenerated %s with %d kinds", snapshotPath, len(current))
		return
	}

	raw, err := os.ReadFile(snapshotPath)
	if err != nil {
		t.Fatalf("registry number snapshot missing -- generate it with `go test ./pkg/catalogkindreflect/ -run TestRegistryNumberSnapshot -update`: %v", err)
	}
	recorded := parseSnapshot(t, string(raw))

	var problems []string
	for name, num := range recorded {
		got, ok := current[name]
		switch {
		case !ok:
			problems = append(problems, fmt.Sprintf("kind %s (was %d) no longer exists -- removals/renames must be deliberate: update the snapshot with -update in the same change", name, num))
		case got != num:
			problems = append(problems, fmt.Sprintf("kind %s moved from %d to %d -- renumbering must be deliberate: update the snapshot with -update in the same change (illegal once the kind is beta/stable)", name, num, got))
		}
	}
	for name, num := range current {
		if _, ok := recorded[name]; !ok {
			problems = append(problems, fmt.Sprintf("kind %s (%d) is not in the snapshot -- add it with -update so the snapshot stays total", name, num))
		}
	}

	sort.Strings(problems)
	for _, p := range problems {
		t.Error(p)
	}
}
