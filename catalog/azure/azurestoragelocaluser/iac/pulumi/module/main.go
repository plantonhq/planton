package module

import (
	"fmt"
	"strings"

	"github.com/pkg/errors"
	azurestoragelocaluserv1alpha1 "github.com/plantonhq/planton/catalog/azure/azurestoragelocaluser/v1alpha1"
	"github.com/plantonhq/planton/pkg/iac/pulumi/pulumimodule/provider/azure/pulumiazureprovider"
	"github.com/pulumi/pulumi-azure/sdk/v6/go/azure/storage"
	"github.com/pulumi/pulumi/sdk/v3/go/pulumi"
)

func Resources(ctx *pulumi.Context, iacInput *azurestoragelocaluserv1alpha1.AzureStorageLocalUserIacInput) error {
	locals := initializeLocals(ctx, iacInput)

	// Build the Azure provider from the IaC input via the shared builder, which resolves
	// the right credential mechanism (static client secret, keyless web identity, or ambient chain).
	azureProvider, err := pulumiazureprovider.Get(ctx, iacInput.ProviderConfig)
	if err != nil {
		return errors.Wrap(err, "failed to create azure provider")
	}

	spec := locals.AzureStorageLocalUser.Spec

	// The account name, parsed from the resolved account ARM ID -- used
	// for the storage_account_name output and to compose the full SFTP
	// login ({account}.{user}). The id must END with
	// /storageAccounts/{name} (matching the Terraform module's anchored
	// regex), so a malformed or over-long id fails loudly here instead
	// of computing a wrong name.
	accountIdParts := strings.Split(locals.StorageAccountId, "/storageAccounts/")
	if len(accountIdParts) != 2 || accountIdParts[1] == "" || strings.Contains(accountIdParts[1], "/") {
		return errors.Errorf("storage_account_id %q is not a storage-account ARM id", locals.StorageAccountId)
	}
	storageAccountName := accountIdParts[1]

	// The local user, addressed by the parent account's ARM ID -- a pure
	// management-plane resource. Credential lifecycle quirks worth
	// knowing (provider behavior, not module invention): the password is
	// generated by Azure at the creation that enables
	// ssh_password_enabled and returned exactly once -- flipping the
	// flag off and back on REGENERATES it; SSH public keys are
	// write-only in Azure's API (the GET never returns them), so the
	// provider keeps them from its own state. At least one auth method
	// is on (enforced in the spec); sending the booleans unconditionally
	// is safe -- false is the provider default on both engines.
	localUserArgs := &storage.LocalUserArgs{
		Name:               pulumi.String(spec.UserName),
		StorageAccountId:   pulumi.String(locals.StorageAccountId),
		SshKeyEnabled:      pulumi.Bool(spec.SshKeyEnabled),
		SshPasswordEnabled: pulumi.Bool(spec.SshPasswordEnabled),
	}

	if spec.HomeDirectory != "" {
		localUserArgs.HomeDirectory = pulumi.String(spec.HomeDirectory)
	}

	// Paired with ssh_key_enabled (the provider rejects keys without the
	// flag, and the flag without keys -- mirrored in the spec so it
	// fails at validate time, not apply time).
	if len(spec.SshAuthorizedKeys) > 0 {
		keys := make(storage.LocalUserSshAuthorizedKeyArray, 0, len(spec.SshAuthorizedKeys))
		for _, authorizedKey := range spec.SshAuthorizedKeys {
			keyArgs := storage.LocalUserSshAuthorizedKeyArgs{
				Key: pulumi.String(authorizedKey.Key),
			}
			if authorizedKey.Description != "" {
				keyArgs.Description = pulumi.String(authorizedKey.Description)
			}
			keys = append(keys, keyArgs)
		}
		localUserArgs.SshAuthorizedKeys = keys
	}

	// Per-resource grants. The API stores permissions as an "rwdlc"
	// letter string; the provider exposes the five booleans -- the spec
	// models the same booleans, so this is a pass-through.
	if len(spec.PermissionScopes) > 0 {
		scopes := make(storage.LocalUserPermissionScopeArray, 0, len(spec.PermissionScopes))
		for _, permissionScope := range spec.PermissionScopes {
			scopes = append(scopes, storage.LocalUserPermissionScopeArgs{
				Service:      pulumi.String(serviceStrings[permissionScope.Service]),
				ResourceName: pulumi.String(permissionScope.ResourceName.GetValue()),
				Permissions: storage.LocalUserPermissionScopePermissionsArgs{
					Read:   pulumi.Bool(permissionScope.Read),
					Write:  pulumi.Bool(permissionScope.Write),
					Delete: pulumi.Bool(permissionScope.Delete),
					List:   pulumi.Bool(permissionScope.List),
					Create: pulumi.Bool(permissionScope.Create),
				},
			})
		}
		localUserArgs.PermissionScopes = scopes
	}

	createdLocalUser, err := storage.NewLocalUser(ctx,
		fmt.Sprintf("%s-%s", storageAccountName, spec.UserName),
		localUserArgs,
		pulumi.Provider(azureProvider))
	if err != nil {
		return errors.Wrapf(err, "failed to create storage local user %s", spec.UserName)
	}

	// Export outputs. sid and password are secret-bearing (the
	// provider marks both sensitive); the password is only ever returned
	// at the creation that enabled password auth -- hand it to the
	// partner over a secure channel.
	ctx.Export(OpLocalUserId, createdLocalUser.ID())
	ctx.Export(OpUserName, createdLocalUser.Name)
	ctx.Export(OpSftpUsername, pulumi.Sprintf("%s.%s", storageAccountName, spec.UserName))
	ctx.Export(OpSid, pulumi.Unsecret(createdLocalUser.Sid))
	ctx.Export(OpPassword, pulumi.ToSecret(createdLocalUser.Password))
	ctx.Export(OpStorageAccountName, pulumi.String(storageAccountName))

	return nil
}
