// The control plane's token. The control plane signs in to the vault with a
// token it reads from a Secret and never renews or looks up itself; the
// operator is what keeps that token alive and what issues a new one when
// it is gone. Every pass: read the Secret, look the token up by its
// accessor, renew it when its remaining life has fallen below half its
// period, and mint anew -- rewriting the Secret -- when the accessor names
// no live token: the platform restored into a fresh namespace (the data is
// back, the Secret is not), a token somebody revoked, an operator away
// longer than the period. A changed accessor is what rolls the control
// plane (control_plane.go), so the pod starts with the new token.
//
// This is the one credential Secret in the operator that is REWRITTEN
// rather than created once. Every other credential the operator issues is
// generated by the operator and therefore final; this one is issued by the
// vault and re-issued by design. Do not "fix" it back to create-once.

// readVaultTokenAccessor reads the accessor of the token the control plane's
// Secret currently holds -- what the control plane component puts on its pod
// template. found is false when the Secret does not exist yet.
func readVaultTokenAccessor(ctx context.Context, c client.Client, planton *v1.PlantonPlatform) (string, bool, error) {
	name := resources.OpenBAOTokenSecretName(planton.Name)
	var secret corev1.Secret
	if err := c.Get(ctx, types.NamespacedName{Name: name, Namespace: planton.Namespace}, &secret); err != nil {
		if apierrors.IsNotFound(err) {
			return "", false, nil
		}
		return "", false, fmt.Errorf("reading the control plane's vault token Secret %s: %w", name, err)
	}
	accessor := string(secret.Data[resources.OpenBAOTokenSecretAccessorKey])
	return accessor, accessor != "", nil
}

// ensureControlPlaneToken keeps the control plane's token alive or mints it,
// with the operator's own session. Returns the accessor of the token the
// Secret now holds.
func ensureControlPlaneToken(ctx context.Context, c client.Client, planton *v1.PlantonPlatform, s *vaultSession, ownerRef *metav1.OwnerReference) (string, error) {
	log := logf.FromContext(ctx).WithValues("component", "openbao")
	name := resources.OpenBAOTokenSecretName(planton.Name)

	var existing corev1.Secret
	err := c.Get(ctx, types.NamespacedName{Name: name, Namespace: planton.Namespace}, &existing)
	if err != nil && !apierrors.IsNotFound(err) {
		return "", fmt.Errorf("reading the control plane's vault token Secret %s: %w", name, err)
	}
	found := err == nil

	if found {
		accessor := string(existing.Data[resources.OpenBAOTokenSecretAccessorKey])
		if accessor != "" && len(existing.Data[resources.OpenBAOTokenSecretTokenKey]) > 0 {
			info, live, err := bootstrap.LookupAccessor(ctx, s.http, s.apiAddr, s.token, accessor)
			if err != nil {
				return "", err
			}
			if live {
				if info.TTL < resources.OpenBAOControlPlaneTokenPeriod/2 {
					if err := bootstrap.RenewAccessor(ctx, s.http, s.apiAddr, s.token, accessor); err != nil {
						return "", err
					}
					log.Info("Renewed the control plane's vault token", "secret", name)
				}
				return accessor, nil
			}
			log.Info("The control plane's vault token is no longer valid; minting a new one", "secret", name)
		}
	}

	tok, err := bootstrap.CreateTokenWithRole(ctx, s.http, s.apiAddr, s.token, resources.OpenBAOControlPlaneRoleName(planton.Name), bootstrap.CreateTokenOptions{
		Policies:    []string{resources.OpenBAOControlPlaneRoleName(planton.Name)},
		DisplayName: resources.OpenBAOControlPlaneRoleName(planton.Name),
		Meta:        map[string]string{"platform": planton.Name, "namespace": planton.Namespace},
	})
	if err != nil {
		return "", err
	}

	desired := &corev1.Secret{
		TypeMeta: metav1.TypeMeta{APIVersion: "v1", Kind: "Secret"},
		ObjectMeta: metav1.ObjectMeta{
			Name:      name,
			Namespace: planton.Namespace,
			Labels: map[string]string{
				"app.kubernetes.io/managed-by": resources.ManagedByLabel,
			},
			Annotations: map[string]string{
				resources.OpenBAOTokenSecretAnnotation: resources.OpenBAOTokenSecretNote(planton.Name),
			},
		},
		Type: corev1.SecretTypeOpaque,
		Data: map[string][]byte{
			resources.OpenBAOTokenSecretTokenKey:    []byte(tok.ClientToken),
			resources.OpenBAOTokenSecretAccessorKey: []byte(tok.Accessor),
		},
	}
	if ownerRef != nil {
		desired.OwnerReferences = []metav1.OwnerReference{*ownerRef}
	}

	if !found {
		if err := c.Create(ctx, desired); err != nil {
			return "", fmt.Errorf("creating the control plane's vault token Secret %s: %w", name, err)
		}
		log.Info("Minted the control plane's vault token", "secret", name)
		return tok.Accessor, nil
	}
	// Rewrite in place by merge patch: the data is replaced whole, the
	// labels and note re-asserted, and whatever else the Secret carries is
	// left as it was.
	updated := existing.DeepCopy()
	if updated.Labels == nil {
		updated.Labels = map[string]string{}
	}
	for k, v := range desired.Labels {
		updated.Labels[k] = v
	}
	if updated.Annotations == nil {
		updated.Annotations = map[string]string{}
	}
	for k, v := range desired.Annotations {
		updated.Annotations[k] = v
	}
	updated.Data = desired.Data
	if err := c.Patch(ctx, updated, client.MergeFrom(&existing)); err != nil {
		return "", fmt.Errorf("rewriting the control plane's vault token Secret %s: %w", name, err)
	}
	log.Info("Re-minted the control plane's vault token", "secret", name)
	return tok.Accessor, nil
}
